import numpy as np

# --- Вхідні дані ---
# Матриця рішень (8x8) — прибутки/збитки
E = np.array([
    [5.2, 3.8, 6.11, 4.12, 5.81, 6.3, 3.55, 6.9],
    [6.5, 7.3, 9.5, 6.91, 6.54, 7.3, 8.2, 8.84],
    [2.8, 2.3, 1.34, 4.42, 3.11, 2.91, 4.7, 2.0],
    [10.5, 8.47, 7.62, 10.82, 7.0, 7.63, 9.73, 8.54],
    [5.0, 7.97, 6.42, 6.53, 5.17, 6.42, 7.59, 6.4],
    [2.95, 4.75, 3.85, 3.93, 4.0, 3.39, 3.51, 4.82],
    [0.5, 2.67, 0.43, 2.21, 0.74, 1.61, 1.8, 2.6],
    [6.6, 9.56, 9.3, 6.86, 9.5, 7.69, 8.47, 6.72]
])

# Ймовірності для критерію Ходжа-Лемана і Гермейєра
p = np.array([0.01, 0.01, 0.05, 0.05, 0.35, 0.25, 0.1, 0.18])

# Параметри для Гурвіца і Ходжа-Лемана
C = 0.3  # HW
v = 0.8  # HL

# --- 1. Критерій Гурвіца ---
# Знаходимо мінімум і максимум по рядках
max_E = np.max(E, axis=1)
min_E = np.min(E, axis=1)

# Обчислюємо оцінку HW для кожного рядка
HW = C*max_E + (1-C)*min_E

print("=== Критерій Гурвіца ===")
for i, val in enumerate(HW, 1):
    print(f"E{i}: {val:.3f}")
best_HW = np.argmax(HW) + 1
print(f"Оптимальний варіант HW: E{best_HW}\n")

# --- 2. Критерій Ходжа-Лемана ---
# Математичне сподівання рядків
expected = E @ p

# Обчислюємо оцінку HL
HL = v*expected + (1-v)*min_E

print("=== Критерій Ходжа-Лемана ===")
for i, val in enumerate(HL, 1):
    print(f"E{i}: {val:.3f}")
best_HL = np.argmax(HL) + 1
print(f"Оптимальний варіант HL: E{best_HL}\n")

# --- 3. Критерій Гермейєра ---
# Визначимо добуток елементів на ймовірності (тільки для збитків)
# Тут для прибутків можна взяти просто min(E*p) по рядку
G = np.min(E * p, axis=1)

print("=== Критерій Гермейєра ===")
for i, val in enumerate(G, 1):
    print(f"E{i}: {val:.3f}")
best_G = np.argmax(G) + 1
print(f"Оптимальний варіант G: E{best_G}\n")

# --- 4. Критерій добутків ---
# Для добутку необхідно, щоб всі елементи були > 0
# Якщо ні, додаємо константу a = |min(E)| + 1
a = abs(np.min(E)) + 1
E_shifted = E + a

# Добуток по рядках
Prod = np.prod(E_shifted, axis=1)

print("=== Критерій добутків ===")
for i, val in enumerate(Prod, 1):
    print(f"E{i}: {val:.3f}")
best_Prod = np.argmax(Prod) + 1
print(f"Оптимальний варіант P: E{best_Prod}\n")
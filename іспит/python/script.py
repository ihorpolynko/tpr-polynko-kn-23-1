import numpy as np
from sympy import symbols, Eq, solve

# --- Початкова спрощена матриця ---
A = np.array([
    [3, -3, 4],
    [-3, 4, -4],
    [4, -4, 5]
], dtype=float)

# --- Символи для стратегій гравця B ---
q1, q2, q3 = symbols('q1 q2 q3')

# Очікувані виграші для стратегій гравця A
E1 = 3*q1 - 3*q2 + 4*q3
E2 = -3*q1 + 4*q2 - 4*q3
E3 = 4*q1 - 4*q2 + 5*q3

# Умова оптимальності: E1 = E2 = E3
eq1 = Eq(E1, E2)
eq2 = Eq(E2, E3)
eq3 = Eq(q1 + q2 + q3, 1)  # сума ймовірностей = 1

# Розв'язок системи
sol = solve([eq1, eq2, eq3], (q1, q2, q3))

print("Оптимальна змішана стратегія гравця B:")
print(sol)

# --- Аналогічно для гравця A ---
p1, p2, p3 = symbols('p1 p2 p3')

# Очікувані виграші для гравця B
F1 = 3*p1 -3*p2 +4*p3
F2 = -3*p1 +4*p2 -4*p3
F3 = 4*p1 -4*p2 +5*p3

eq_a1 = Eq(F1, F2)
eq_a2 = Eq(F2, F3)
eq_a3 = Eq(p1 + p2 + p3, 1)

sol_A = solve([eq_a1, eq_a2, eq_a3], (p1, p2, p3))
print("\nОптимальна змішана стратегія гравця A:")
print(sol_A)

# --- Ціна гри ---
# Використаємо очікуваний виграш для будь-якої стратегії гравця A
v = E1.subs(sol)
print("\nЦіна гри:", v)
